#!/usr/bin/env node
/**
 * 1.4.3 (QA V142-5/V142-6), 1.4.4 (V143-6): generates the email ALLOW lists (scripts/emailLists.js has the rules):
 *  - src/core/emailChars.ts      the 1.4.3 list (lower-case Latin/Greek/Cyrillic, 9 Indic scripts);
 *  - src/core/emailCharsWide.ts  the prepared wider list + the ZWNJ/ZWJ context regex;
 *  - the <email-letters> block of firestore.rules, for the list src/core/emailPolicy.ts makes active
 *    (EMAIL_WIDE_ACTIVE; false in 1.4.4). rules-tests check the block equals the active list.
 * Format (Cf), control (Cc), private-use (Co), unassigned (Cn) and separator characters are never in either list.
 * Run: node scripts/gen-email-chars.js   (--check: exit 1 if a generated file is out of date, write nothing)
 */
const fs = require('fs');
const path = require('path');
const L = require('./emailLists');

const root = path.join(__dirname, '..');
const check = process.argv.includes('--check');
const wideActive = /export const EMAIL_WIDE_ACTIVE = true;/.test(fs.readFileSync(path.join(root, 'src/core/emailPolicy.ts'), 'utf8'));
const n = L.narrow();
const w = [...n, ...L.wideExtra()];
const narrowTs = `/**
 * GENERATED by scripts/gen-email-chars.js (Unicode ${process.versions.unicode}) – do not edit by hand.
 * 1.4.3 (QA V142-5/V142-6): the non-ASCII letters an email address may contain (an ALLOW list): lower-case letters
 * of Latin, Greek and Cyrillic (Ll only), and the letters, marks and digits of Devanagari, Bengali, Gurmukhi,
 * Gujarati, Oriya, Tamil, Telugu, Kannada and Malayalam – NFC-stable and already case-folded. No format, control,
 * private-use, unassigned or separator character is in it. ${n.length} code points in ${L.ranges(n).length} ranges.
 */
/** Body of a JS character class (BMP only). */
export const EMAIL_LETTERS = '${L.jsClass(n)}';
/** The same class for firestore.rules (emailLetters()): the characters themselves, ranges as a-b. */
export const EMAIL_LETTERS_RULES = '${L.litClass(n)}';
export const EMAIL_LETTER_COUNT = ${n.length};
`;
const wideTs = `/**
 * GENERATED by scripts/gen-email-chars.js (Unicode ${process.versions.unicode}) – do not edit by hand.
 * 1.4.4 (QA V143-6): the WIDER email allow list – prepared and tested, INACTIVE unless src/core/emailPolicy.ts
 * EMAIL_WIDE_ACTIVE is true. The 1.4.3 list plus Ol Chiki, Meetei Mayek and Arabic letters for Urdu/Kashmiri
 * (${w.length - n.length} more code points; see scripts/emailLists.js), and ZWNJ/ZWJ only between two letters/marks of the same
 * Indic script (EMAIL_JOIN_RE). ${w.length} code points in ${L.ranges(w).length} ranges.
 */
/** Body of a JS character class (BMP only), without ZWNJ/ZWJ. */
export const EMAIL_LETTERS_WIDE = '${L.jsClass(w)}';
/** Whole-address test: every U+200C/U+200D sits between two letters/marks of one Indic script. */
export const EMAIL_JOIN_RE = new RegExp('${L.joinRegex(false).replace(/\\/g, '\\\\')}');
export const EMAIL_LETTER_COUNT_WIDE = ${w.length};
`;
const rulesPath = path.join(root, 'firestore.rules');
const rules = fs.readFileSync(rulesPath, 'utf8');
if (!L.BLOCK_RE.test(rules)) throw new Error('firestore.rules: <email-letters> block not found');
const rulesNew = rules.replace(L.BLOCK_RE, () => L.rulesBlock(wideActive)); // a function: the block contains '$'
const files = [[path.join(root, 'src/core/emailChars.ts'), narrowTs], [path.join(root, 'src/core/emailCharsWide.ts'), wideTs], [rulesPath, rulesNew]];
let stale = 0;
for (const [f, text] of files) {
  const cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
  if (cur === text) continue;
  stale++;
  if (check) console.log(`out of date: ${path.relative(root, f)}`);
  else fs.writeFileSync(f, text);
}
console.log(`narrow ${n.length}, wide ${w.length} code points; active: ${wideActive ? 'WIDE' : 'narrow (1.4.3)'}; ${check ? `${stale} stale` : `${stale} written`}`);
if (check && stale) process.exit(1);
