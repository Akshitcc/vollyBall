/**
 * 1.4.3 / 1.4.4 (QA V142-5/V142-6, V143-6): the email ALLOW lists, computed from Node's Unicode data. Shared by
 * scripts/gen-email-chars.js (writes src/core/emailChars.ts, src/core/emailCharsWide.ts and the generated block of
 * firestore.rules) and rules-tests (which build the wide rules variant from the same block).
 *
 * NARROW (active since 1.4.3): lower-case Latin/Greek/Cyrillic (Ll), letters/marks/digits of the 9 Indic scripts.
 * WIDE (1.4.4, prepared and INACTIVE – src/core/emailPolicy.ts EMAIL_WIDE_ACTIVE): NARROW plus
 *  - Ol Chiki (Santali): letters, modifier letters, digits (U+1C50–1C7D; not the punctuation U+1C7E–7F);
 *  - Meetei Mayek (Manipuri): letters, marks, digits (U+ABC0–ABFF, Extensions U+AAE0–AAFF; no punctuation);
 *  - Arabic for Urdu and Kashmiri: the Arabic block's letters (no tatweel U+0640, no Quranic signs), the
 *    vowel marks U+064B–065F and U+0670, and the Extended Arabic-Indic digits U+06F0–06F9 only (the Arabic-Indic
 *    U+0660–0669 look the same and would let two addresses look identical);
 *  - ZWNJ/ZWJ (U+200C/U+200D) only between two letters/marks of the SAME Indic script (Devanagari…Malayalam),
 *    e.g. क्‍ष – never at an edge, next to ASCII, between scripts, or doubled.
 */
const CASED = [
  [0x00c0, 0x00ff], [0x0100, 0x017f], [0x0180, 0x024f], [0x1e00, 0x1eff], [0x0370, 0x03ff], [0x1f00, 0x1fff], [0x0400, 0x04ff], [0x0500, 0x052f],
];
const INDIC = [
  [0x0900, 0x097f, 'Devanagari'], [0x0980, 0x09ff, 'Bengali'], [0x0a00, 0x0a7f, 'Gurmukhi'], [0x0a80, 0x0aff, 'Gujarati'],
  [0x0b00, 0x0b7f, 'Oriya'], [0x0b80, 0x0bff, 'Tamil'], [0x0c00, 0x0c7f, 'Telugu'], [0x0c80, 0x0cff, 'Kannada'], [0x0d00, 0x0d7f, 'Malayalam'],
];
const WIDE_EXTRA = [
  [0x1c50, 0x1c7d, 'Ol Chiki'], [0xaae0, 0xaaff, 'Meetei Mayek Extensions'], [0xabc0, 0xabff, 'Meetei Mayek'],
];
const ARABIC = [[0x0620, 0x064a], [0x064b, 0x065f], [0x066e, 0x06d3], [0x06d5, 0x06d5], [0x0670, 0x0670], [0x06ee, 0x06ef], [0x06f0, 0x06f9], [0x06fa, 0x06fc], [0x06ff, 0x06ff]];
const FOLD_SOURCES = new Set([0x3c2, 0x17f, 0xb5, 0x3d0, 0x3d1, 0x3d5, 0x3d6, 0x3f0, 0x3f1, 0x3f5, 0x1e9b, 0x1fbe, 0x345]);
const ch = (cp) => String.fromCodePoint(cp);
const stable = (c) => c.normalize('NFC') === c && c.toLowerCase() === c;
const isLMN = (c) => /^[\p{L}\p{Mn}\p{Mc}\p{Nd}]$/u.test(c) && !/^[\p{Lu}\p{Lt}]$/u.test(c) && stable(c);

function collect(blocks, test) {
  const out = [];
  for (const [lo, hi] of blocks) for (let cp = lo; cp <= hi; cp++) if (test(ch(cp), cp)) out.push(cp);
  return out;
}
const narrow = () => [
  ...collect(CASED, (c, cp) => /^\p{Ll}$/u.test(c) && stable(c) && !FOLD_SOURCES.has(cp)),
  ...collect(INDIC, isLMN),
];
const wideExtra = () => [...new Set([
  ...collect(ARABIC, (c) => isLMN(c) && !/^\p{Lm}$/u.test(c)),
  ...collect(WIDE_EXTRA, isLMN),
])];
/** Letters and marks (no digits) of one Indic script: the neighbours a ZWNJ/ZWJ may sit between. */
const joinClass = ([lo, hi]) => collect([[lo, hi]], (c) => isLMN(c) && !/^\p{Nd}$/u.test(c));

function ranges(cps) {
  const r = [];
  for (const cp of [...new Set(cps)]) { // generation order (as 1.4.3), not sorted
    const last = r[r.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else r.push([cp, cp]);
  }
  return r;
}
const hex = (n) => n.toString(16).toUpperCase().padStart(4, '0');
const jsClass = (cps) => ranges(cps).map(([a, b]) => (a === b ? `\\u${hex(a)}` : `\\u${hex(a)}-\\u${hex(b)}`)).join('');
const litClass = (cps) => ranges(cps).map(([a, b]) => (a === b ? ch(a) : `${ch(a)}-${ch(b)}`)).join('');

/** Regex body: every ZWNJ/ZWJ sits between two letters/marks of the same Indic script. */
function joinRegex(lit) {
  const cls = (cps) => `[${lit ? litClass(cps) : jsClass(cps)}]`;
  const zw = lit ? '\\x{200C}\\x{200D}' : '\\u200C\\u200D';
  const alts = INDIC.map((b) => { const c = cls(joinClass(b)); return `${c}(?:[${zw}]${c})+`; });
  return `^(?:[^${zw}]|${alts.join('|')})*$`;
}

/** The generated block of firestore.rules (between the markers), for the narrow or the wide list. */
function rulesBlock(wide) {
  const lit = litClass(wide ? [...narrow(), ...wideExtra()] : narrow());
  // a rules string literal: a backslash is written twice
  const letters = wide ? `\\\\x{200C}\\\\x{200D}${lit}` : lit;
  const join = wide
    ? `return !e.matches('.*[\\\\x{200C}\\\\x{200D}].*') || e.matches('${joinRegex(true).replace(/\\/g, '\\\\')}');`
    : 'return true; // the narrow list has no ZWNJ/ZWJ';
  return [
    `    // <email-letters> GENERATED by scripts/gen-email-chars.js from src/core/emailPolicy.ts (${wide ? 'WIDE' : 'NARROW'} list) – do not edit by hand`,
    '    function emailLetters() {',
    `      return '${letters}';`,
    '    }',
    '    function emailJoinOk(e) {',
    `      ${join}`,
    '    }',
    '    // </email-letters>',
  ].join('\n');
}
const BLOCK_RE = /    \/\/ <email-letters>[\s\S]*?\/\/ <\/email-letters>/;

module.exports = { narrow, wideExtra, jsClass, litClass, joinRegex, rulesBlock, BLOCK_RE, ranges };
